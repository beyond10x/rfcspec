    /// The body of the generated test `name`.
    fn test_body(lib: &str, name: &str) -> String {
        let start = lib
            .find(&format!("fn {name}() {{"))
            .unwrap_or_else(|| panic!("no test {name}"));
        let rest = &lib[start..];
        rest[..rest.find("\n    }\n").unwrap()].to_string()
    }

    fn header(fields: &[(&str, &str)]) -> String {
        let all = [
            "fin",
            "rsv1",
            "rsv2",
            "rsv3",
            "opcode",
            "mask",
            "payload_len",
            "extended_payload_length_16",
            "extended_payload_length_64",
            "masking_key",
        ];
        let values: Vec<String> = all
            .iter()
            .map(|name| {
                let value = fields
                    .iter()
                    .find(|(field, _)| field == name)
                    .map(|(_, v)| (*v).to_string())
                    .unwrap_or_else(|| {
                        if name.starts_with("ext") || *name == "masking_key" {
                            "None".into()
                        } else {
                            "0".into()
                        }
                    });
                format!("                {name}: {value}")
            })
            .collect();
        format!("FrameHeader {{\n{}\n            }}", values.join(",\n"))
    }

