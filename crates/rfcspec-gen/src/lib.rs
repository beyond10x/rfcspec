#![forbid(unsafe_code)]
//! S6: generate a Rust codec crate from the overlay's one layout, in one of two shapes.
//!
//! - A layout with an epoch is one integer field of 8, 16 or 32 bits counting seconds from that
//!   epoch; the crate gets a newtype, `parse` (exactly the field's octets, else an error) and
//!   `print`, and one test per numeric example of the RFC. An example that does not fit the field
//!   and has no finding is refused.
//! - A layout without an epoch is a header of unsigned big-endian fields of 1 to 64 bits packed
//!   most significant bit first, a field present only when an earlier one has a value, with value
//!   constraints ([`fields`]); the crate gets a struct, `parse`, `print` and the length the layout
//!   names, one test per octet example of the RFC, and the layout vectors of design section 11.
//!
//! An example a review finding names is skipped by that finding.

mod fields;

use anyhow::{Context, Result, bail, ensure};
use rfcspec_model::{Catalogue, Generated, Layout, NumericExample, Overlay};

/// Generate the codec crate `rfc<N>-<profile>`: `Cargo.toml` and `src/lib.rs`.
pub fn rust(overlay: &Overlay, catalogue: &Catalogue, profile: &str) -> Result<Vec<Generated>> {
    let [layout] = overlay.layouts.as_slice() else {
        bail!(
            "code generation needs exactly one layout, the overlay has {}",
            overlay.layouts.len()
        );
    };
    let library = match &layout.epoch {
        Some(epoch) => epoch_library(overlay, catalogue, profile, layout, epoch)?,
        None => fields::library(overlay, catalogue, profile, layout)?,
    };
    Ok(vec![
        Generated {
            file: "Cargo.toml".into(),
            text: manifest(overlay, profile, layout),
        },
        Generated {
            file: "src/lib.rs".into(),
            text: library,
        },
    ])
}

fn manifest(overlay: &Overlay, profile: &str, layout: &Layout) -> String {
    format!(
        r#"[package]
name = "rfc{rfc}-{profile}"
description = "Generated by rfcspec from the {profile} profile: the RFC {rfc} {layout} layout as a codec."
version.workspace = true
edition.workspace = true
license.workspace = true
repository.workspace = true
publish.workspace = true

[lints]
workspace = true
"#,
        rfc = overlay.rfc,
        layout = layout.name,
    )
}

/// The library of a one-field layout counting seconds from an epoch.
fn epoch_library(
    overlay: &Overlay,
    catalogue: &Catalogue,
    profile: &str,
    layout: &Layout,
    epoch_date: &str,
) -> Result<String> {
    let [field] = layout.fields.as_slice() else {
        bail!(
            "layout {}: code generation needs exactly one field, found {}",
            layout.name,
            layout.fields.len()
        );
    };
    ensure!(
        matches!(field.bits, 8 | 16 | 32),
        "layout {}: field {} has {} bits; 8, 16 or 32 are supported",
        layout.name,
        field.name,
        field.bits
    );
    let (from_bytes, to_bytes) = match field.order.as_str() {
        "big-endian" => ("from_be_bytes", "to_be_bytes"),
        "little-endian" => ("from_le_bytes", "to_le_bytes"),
        other => bail!("layout {}: unknown byte order {other}", layout.name),
    };
    let int = format!("{}{}", if field.signed { "i" } else { "u" }, field.bits);
    let (min, max) = if field.signed {
        (-(1i64 << (field.bits - 1)), (1i64 << (field.bits - 1)) - 1)
    } else {
        (0, (1i64 << field.bits) - 1)
    };
    let octets = field.bits / 8;
    let epoch = epoch_unix_seconds(layout, epoch_date)?;
    let name = camel(&layout.name);

    let mut tests = String::new();
    for example in &catalogue.examples {
        if let Some(finding) = overlay.findings.iter().find(|f| f.item == example.id) {
            tests.push_str(&format!(
                "\n    // {}: no test, review finding {}.\n",
                example.id, finding.id
            ));
            continue;
        }
        ensure!(
            (min..=max).contains(&example.seconds),
            "example {} ({}) does not fit {int} and no review finding names it",
            example.id,
            example.seconds
        );
        let (date, unix) = example_date(example)?;
        tests.push_str(&format!(
            r#"
    #[test]
    fn example_{id}_{date_name}() {{
        let value = {name}({seconds});
        assert_eq!(value.unix_seconds(), {unix});
        assert_eq!(parse(&print(value)), Ok(value));
    }}
"#,
            id = example.id.to_lowercase(),
            date_name = date.replace('-', "_"),
            seconds = example.seconds,
        ));
    }

    let library = format!(
        r#"#![forbid(unsafe_code)]
//! Generated by `rfcspec generate rust` from the `{profile}` profile's overlay; do not edit.
//!
//! RFC {rfc} layout `{layout}`: one {bits}-bit {order} field `{field}`, the number of seconds since
//! {epoch_date} 00:00 GMT.

use std::fmt;

/// Octets on the wire.
pub const OCTETS: usize = {octets};

/// The Unix time of the epoch the value counts from.
pub const EPOCH_UNIX_SECONDS: i64 = {epoch};

/// The `{layout}` value.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct {name}(pub {int});

impl {name} {{
    /// The same instant as Unix time.
    pub fn unix_seconds(self) -> i64 {{
        i64::from(self.0) + EPOCH_UNIX_SECONDS
    }}
}}

/// Why bytes are not a `{layout}` value.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Error {{
    /// Not exactly [`OCTETS`] octets.
    Length {{ found: usize }},
}}

impl fmt::Display for Error {{
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {{
        match self {{
            Error::Length {{ found }} => write!(f, "expected {{OCTETS}} octets, found {{found}}"),
        }}
    }}
}}

impl std::error::Error for Error {{}}

/// Parse exactly [`OCTETS`] octets; any other length is an error.
pub fn parse(bytes: &[u8]) -> Result<{name}, Error> {{
    let octets: [u8; OCTETS] = bytes
        .try_into()
        .map_err(|_| Error::Length {{ found: bytes.len() }})?;
    Ok({name}({int}::{from_bytes}(octets)))
}}

/// The octets of a value.
pub fn print(value: {name}) -> [u8; OCTETS] {{
    value.0.{to_bytes}()
}}

#[cfg(test)]
mod tests {{
    use super::*;

    #[test]
    fn any_other_length_is_an_error() {{
        for length in [0, OCTETS - 1, OCTETS + 1] {{
            let bytes = vec![0u8; length];
            assert_eq!(parse(&bytes), Err(Error::Length {{ found: length }}));
        }}
    }}
{tests}}}
"#,
        rfc = overlay.rfc,
        layout = layout.name,
        bits = field.bits,
        order = field.order,
        field = field.name,
    );

    Ok(library)
}

fn camel(name: &str) -> String {
    name.split(['-', '_'])
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|first| first.to_ascii_uppercase().to_string() + chars.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn epoch_unix_seconds(layout: &Layout, epoch: &str) -> Result<i64> {
    let parts: Vec<i64> = epoch
        .split('-')
        .map(str::parse)
        .collect::<Result<_, _>>()
        .with_context(|| {
            format!(
                "layout {}: epoch {:?} is not YYYY-MM-DD",
                layout.name, epoch
            )
        })?;
    let [year, month, day] = parts.as_slice() else {
        bail!(
            "layout {}: epoch {:?} is not YYYY-MM-DD",
            layout.name,
            epoch
        );
    };
    Ok(days_from_civil(*year, *month, *day) * 86_400)
}

/// The date of an example (`... corresponds to 00:00  1 Jan 1970 GMT,`) as `YYYY-MM-DD` and Unix
/// time.
fn example_date(example: &NumericExample) -> Result<(String, i64)> {
    let refuse = || {
        format!(
            "example {}: no `HH:MM D Mon YYYY GMT` date in {:?}",
            example.id, example.text
        )
    };
    let (_, date) = example
        .text
        .split_once(" corresponds to ")
        .with_context(refuse)?;
    let tokens: Vec<&str> = date.split_whitespace().collect();
    let [clock, day, month, year, zone, ..] = tokens.as_slice() else {
        bail!(refuse());
    };
    ensure!(zone.trim_end_matches([',', '.']) == "GMT", refuse());
    let (hours, minutes) = clock.split_once(':').with_context(refuse)?;
    let month = [
        "Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec",
    ]
    .iter()
    .position(|name| name == month)
    .with_context(refuse)? as i64
        + 1;
    let number = |text: &str| text.parse::<i64>().with_context(refuse);
    let (year, day) = (number(year)?, number(day)?);
    let unix =
        days_from_civil(year, month, day) * 86_400 + number(hours)? * 3_600 + number(minutes)? * 60;
    Ok((format!("{year:04}-{month:02}-{day:02}"), unix))
}

/// Days from 1970-01-01 to a proleptic Gregorian date.
fn days_from_civil(year: i64, month: i64, day: i64) -> i64 {
    let year = if month <= 2 { year - 1 } else { year };
    let era = year.div_euclid(400);
    let year_of_era = year - era * 400;
    let day_of_year = (153 * ((month + 9) % 12) + 2) / 5 + day - 1;
    let day_of_era = year_of_era * 365 + year_of_era / 4 - year_of_era / 100 + day_of_year;
    era * 146_097 + day_of_era - 719_468
}

