//! What every generated page shares: its front matter and header line, and the escaping that keeps
//! a page passive Markdown.

/// The first line of every generated page's front matter.
pub const FRONT_MATTER_HEADER: &str = "# generated by rfcspec-docs, do not edit";
/// The line every generated page carries directly after its front matter.
pub const HEADER: &str = "<!-- generated by rfcspec-docs, do not edit -->";
/// A file in the repository on GitHub, by path.
pub const SOURCE: &str = "https://github.com/beyond10x/rfcspec/blob/main";
/// The path the site is served under, as `docusaurus.config.ts` sets `baseUrl`.
pub const BASE_URL: &str = "/rfcspec/";

/// What the front matter of one generated page says.
pub struct Meta<'a> {
    pub title: &'a str,
    pub label: &'a str,
    pub description: &'a str,
    pub position: u32,
}

fn yaml_string(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

/// The front matter of a generated page (the generator line, title, label, sidebar position,
/// description, and no edit link), then [`HEADER`].
pub fn front_matter(meta: &Meta<'_>) -> String {
    format!(
        "---\n{FRONT_MATTER_HEADER}\ntitle: {}\nsidebar_label: {}\nsidebar_position: {}\ndescription: {}\ncustom_edit_url: null\n---\n\n{HEADER}\n\n",
        yaml_string(meta.title),
        yaml_string(meta.label),
        meta.position,
        yaml_string(
            &meta
                .description
                .split_whitespace()
                .collect::<Vec<_>>()
                .join(" ")
        ),
    )
}

/// One block of a Markdown text.
pub enum Block<'a> {
    /// Consecutive non-blank lines outside a code fence, joined by `\n`: a paragraph, a list or a
    /// table. Code spans may wrap lines inside it.
    Prose(String),
    /// A blank line, a fence line, or a line inside a fence, as it is.
    Verbatim(&'a str),
}

/// The blocks of `text`, each with the index of its first line, and whether a fence is left open.
pub fn blocks(text: &str) -> (Vec<(usize, Block<'_>)>, bool) {
    let mut out = Vec::new();
    let mut fenced = false;
    let mut prose: Option<(usize, Vec<&str>)> = None;
    let flush = |prose: &mut Option<(usize, Vec<&str>)>, out: &mut Vec<(usize, Block<'_>)>| {
        if let Some((first, lines)) = prose.take() {
            out.push((first, Block::Prose(lines.join("\n"))));
        }
    };
    for (n, line) in text.lines().enumerate() {
        let fence = line.trim_start().starts_with("```");
        if fence || fenced || line.trim().is_empty() {
            flush(&mut prose, &mut out);
            if fence {
                fenced = !fenced;
            }
            out.push((n, Block::Verbatim(line)));
        } else {
            prose.get_or_insert_with(|| (n, Vec::new())).1.push(line);
        }
    }
    flush(&mut prose, &mut out);
    (out, fenced)
}

/// Markdown prose with braces and angle brackets escaped outside code spans, so the page stays
/// passive Markdown under an MDX reader. Text whose backticks do not pair is escaped whole.
pub fn passive(line: &str) -> String {
    let segments: Vec<&str> = line.split('`').collect();
    let paired = segments.len() % 2 == 1;
    segments
        .iter()
        .enumerate()
        .map(|(n, segment)| {
            if paired && n % 2 == 1 {
                format!("`{segment}`")
            } else {
                let escaped = segment
                    .replace('{', "\\{")
                    .replace('}', "\\}")
                    .replace('<', "&lt;");
                if paired || n == 0 {
                    escaped
                } else {
                    format!("\\`{escaped}")
                }
            }
        })
        .collect()
}

/// `text` on one line, safe in a table cell outside a code span.
pub fn cell(text: &str) -> String {
    passive(&text.split_whitespace().collect::<Vec<_>>().join(" ")).replace('|', "\\|")
}

/// Where `text`, a Markdown page, holds a brace or a capitalised tag outside code, by the first
/// line of the paragraph that holds it. Code spans may wrap lines, so a paragraph is read whole.
pub fn passive_problems(text: &str) -> Vec<usize> {
    let body_start = if text.starts_with("---\n") {
        text.lines()
            .skip(1)
            .position(|line| line == "---")
            .map_or(0, |n| n + 2)
    } else {
        0
    };
    let mut problems = Vec::new();
    let body: String = text
        .lines()
        .skip(body_start)
        .map(|line| format!("{line}\n"))
        .collect();
    for (first, block) in blocks(&body).0 {
        let Block::Prose(paragraph) = block else {
            continue;
        };
        let first = first + body_start;
        let segments: Vec<&str> = paragraph.split('`').collect();
        let paired = segments.len() % 2 == 1;
        let prose: String = segments
            .iter()
            .enumerate()
            .filter(|(i, _)| !paired || i % 2 == 0)
            .map(|(_, s)| s.replace("\\{", "").replace("\\}", ""))
            .collect();
        let tag = prose
            .as_bytes()
            .windows(2)
            .any(|w| w[0] == b'<' && (w[1].is_ascii_uppercase() || w[1] == b'{'));
        if prose.contains('{') || prose.contains('}') || tag {
            problems.push(first + 1);
        }
    }
    problems
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn front_matter_opens_with_the_generator_line_and_has_no_edit_link() {
        let page = front_matter(&Meta {
            title: "The \"design\"",
            label: "Design",
            description: "Two\n  lines.",
            position: 9,
        });
        assert_eq!(
            page,
            "---\n# generated by rfcspec-docs, do not edit\ntitle: \"The \\\"design\\\"\"\nsidebar_label: \"Design\"\nsidebar_position: 9\ndescription: \"Two lines.\"\ncustom_edit_url: null\n---\n\n<!-- generated by rfcspec-docs, do not edit -->\n\n"
        );
    }

    #[test]
    fn passive_escapes_prose_and_keeps_code_spans() {
        assert_eq!(
            passive("a {b} <Tag> `c {d} <E>` f"),
            "a \\{b\\} &lt;Tag> `c {d} <E>` f"
        );
        assert_eq!(passive("one ` unpaired {x}"), "one \\` unpaired \\{x\\}");
        assert_eq!(passive("plain"), "plain");
    }

    #[test]
    fn cells_escape_pipes_and_join_lines() {
        assert_eq!(cell("a | b\n  c"), "a \\| b c");
    }

    #[test]
    fn a_cell_with_braces_a_tag_and_a_pipe_stays_passive() {
        let escaped = cell("send {x}, <Tag> | y");
        assert_eq!(escaped, "send \\{x\\}, &lt;Tag> \\| y");
        assert!(passive_problems(&format!("| a | {escaped} |\n")).is_empty());
        assert_eq!(passive_problems("| a | send {x}, <Tag> |\n"), [1]);
    }

    #[test]
    fn braces_and_capitalised_tags_outside_code_are_refused() {
        let text = "---\ntitle: {x}\n---\n\nfine `{a}` and \\{b\\}\n\nbad {c}\n\nbad <Tag>\n\nfine a < b and `{wrapped\nspan}`\n\n```\n{d}\n```\n";
        assert_eq!(passive_problems(text), [7, 9]);
    }
}
