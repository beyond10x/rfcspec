//! The design page, `website/docs/design.md`, from `docs/design/rfcspec.md`: the same text with its
//! title moved into front matter and its prose made passive, so the site never carries a copy that
//! differs from the repository's design.

use anyhow::{Result, ensure};

use crate::page::{Block, Meta, blocks, front_matter, passive};

/// The design document, relative to the repository root.
pub const SOURCE: &str = "docs/design/rfcspec.md";
/// The page, relative to the repository root.
pub const PAGE: &str = "website/docs/design.md";

/// The page for the design document `text`.
pub fn render(text: &str) -> Result<String> {
    let mut lines = text.lines();
    let title = lines.next().unwrap_or_default();
    ensure!(
        title.starts_with("# "),
        "{SOURCE} must open with a level-one heading"
    );
    let mut page = front_matter(&Meta {
        title: title.trim_start_matches("# "),
        label: "Design",
        description: "The RFCspec design: decisions, the pipeline from an RFC to ESS, the catalogue, communication semantics, the ESS gaps, the WebSocket example and the milestones.",
        position: 20,
    });
    page.push_str(&format!(
        ":::note[Generated]\nThis page is [`{SOURCE}`]({}/{SOURCE}) as it stands on `main`, generated by `rfcspec-docs`.\n:::\n",
        crate::page::SOURCE
    ));
    let rest: String = lines.map(|line| format!("{line}\n")).collect();
    let (blocks, open) = blocks(&rest);
    ensure!(!open, "{SOURCE} has a code fence that is never closed");
    for (_, block) in blocks {
        match block {
            Block::Prose(text) => page.push_str(&passive(&text)),
            Block::Verbatim(line) => page.push_str(line),
        }
        page.push('\n');
    }
    Ok(page)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_title_moves_to_front_matter_and_code_stays_verbatim() {
        let page =
            render("# RFCspec: a title\n\nProse {x} <Y>.\n\n```yaml\na: {b: 1}\n```\n").unwrap();
        assert!(page.contains("title: \"RFCspec: a title\"\n"));
        assert!(!page.contains("\n# RFCspec"));
        assert!(page.contains("Prose \\{x\\} &lt;Y>.\n"));
        assert!(page.contains("```yaml\na: {b: 1}\n```\n"));
    }

    #[test]
    fn a_code_span_that_wraps_a_line_stays_code() {
        let page = render("# T\n\nsee `{a,\nb}` and {c}\n").unwrap();
        assert!(page.contains("see `{a,\nb}` and \\{c\\}\n"), "{page}");
    }

    #[test]
    fn a_document_without_a_title_or_with_an_open_fence_is_refused() {
        assert!(render("no title\n").is_err());
        assert!(render("# T\n```\nopen\n").is_err());
    }
}
